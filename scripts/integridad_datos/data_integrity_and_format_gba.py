from shapely.validation import make_valid

def auditar_y_mostrar_en_consola(gdf_edificios, codigo_municipio="General"):
    """
    Audita las huellas de edificios directamente en memoria y muestra
    las métricas de integridad y nulos por consola.
    """
    total_inicial = len(gdf_edificios)
    print(f"=== REPORTE DE AUDITORÍA: MUNICIPIO / LOTE {codigo_municipio} ===")
    print(f"Total de registros iniciales: {total_inicial}\n")

    # 1. Control del Sistema de Referencia (CRS)
    if gdf_edificios.crs != "EPSG:4326":
        gdf_edificios = gdf_edificios.to_crs("EPSG:4326")
        print("-> [CRS] Reproyectado exitosamente a EPSG:4326 (WGS 84).")
    else:
        print("-> [CRS] OK: Ya se encuentra en EPSG:4326.")

    # 2. Conteo y eliminación de geometrías nulas o vacías
    nulos_geom = gdf_edificios['geometry'].isna().sum()
    vacios_geom = gdf_edificios.geometry.is_empty.sum()

    # Conteo de nulos por columna (formato exacto requerido)
    print("\nValores nulos por columna:")
    nulos_por_columna = gdf_edificios.isna().sum()
    for col, val in nulos_por_columna.items():
        print(f"{col:<20} {val}")

    print(f"dtype: {gdf_edificios.dtypes.iloc[0] if not gdf_edificios.empty else 'N/A'}\n")

    # Filtrar nulos/vacíos para la limpieza
    gdf_limpio = gdf_edificios.dropna(subset=['geometry']).copy()
    gdf_limpio = gdf_limpio[~gdf_limpio.geometry.is_empty]

    # 3. Detección y corrección topológica
    invalidos = (~gdf_limpio['geometry'].is_valid).sum()
    if invalidos > 0:
        print(f"-> [Topología] Se detectaron {invalidos} geometrías inválidas. Aplicando make_valid()...")
        gdf_limpio['geometry'] = gdf_limpio['geometry'].apply(lambda geom: make_valid(geom) if not geom.is_valid else geom)
    else:
        print("-> [Topología] OK: No se detectaron auto-intersecciones ni geometrías inválidas.")

    # 4. Cálculo de área proyectada para la UPME (MAGNA-SIRGAS / Origen Nacional)
    gdf_proj = gdf_limpio.to_crs("EPSG:9377")
    gdf_limpio['area_m2'] = gdf_proj.geometry.area

    # 5. Resumen final de integridad
    total_final = len(gdf_limpio)
    descartados = total_inicial - total_final
    print(f"\n--- Resumen de Integridad ---")
    print(f"Registros válidos listos para MongoDB: {total_final}")
    print(f"Registros descartados: {descartados}")
    print("==================================================\n")

    return gdf_limpio
