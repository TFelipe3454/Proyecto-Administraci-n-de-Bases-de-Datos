import os
import pandas as pd
import geopandas as gpd
from shapely import wkt
from shapely.validation import make_valid
import gc

archivo_csv = 'open_buildings_v3_polygons_ne_110m_COL.csv.gz'

# 1. Cargar el Excel oficial de municipios PDET y extraer los códigos
df_pdet_excel = pd.read_excel('MunicipiosPDET.xlsx')
codigos_pdet = df_pdet_excel['Código DANE Municipio'].astype(str).str.zfill(5).tolist()

# 2. Cargar el mapa general de Colombia y filtrar únicamente los municipios PDET
mgn_colombia = gpd.read_file('MGN_ADM_MPIO_GRAFICO.geojson')
pdet_gdf = mgn_colombia[mgn_colombia['mpio_cdpmp'].isin(codigos_pdet)].copy()

print(f"-> Municipios PDET cargados desde el Excel: {len(pdet_gdf)}")

if os.path.exists(archivo_csv):
    tamano_mb = os.path.getsize(archivo_csv) / (1024 * 1024)
    print(f"Tamaño del archivo de edificios en disco: {tamano_mb:.2f} MB\n")

chunk_size = 100000
chunks_filtrados_y_limpios = []
total_originales = 0

print("--> Filtrando edificios de Google Open Buildings para los municipios PDET...")

# 3. Procesar el archivo masivo de edificios por lotes (chunks)
for i, chunk in enumerate(pd.read_csv(archivo_csv, compression='gzip', chunksize=chunk_size)):
    total_originales += len(chunk)

    # Filtrar confianza y nulos básicos
    chunk_clean = chunk[(chunk['confidence'] >= 0.7) & (chunk['geometry'].notna())].copy()
    if len(chunk_clean) == 0:
        continue

    # Convertir WKT a geometrías
    chunk_clean['geometry'] = chunk_clean['geometry'].apply(wkt.loads)
    gdf_chunk = gpd.GeoDataFrame(chunk_clean, geometry='geometry', crs="EPSG:4326")

    # Asegurar CRS compatible
    if gdf_chunk.crs != pdet_gdf.crs:
        pdet_gdf = pdet_gdf.to_crs(gdf_chunk.crs)

    # Filtro espacial usando los polígonos derivados del Excel
    gdf_chunk_pdet = gpd.sjoin(gdf_chunk, pdet_gdf, how="inner", predicate="intersects")

    if len(gdf_chunk_pdet) > 0:
        # Corrección topológica
        invalidos = (~gdf_chunk_pdet['geometry'].is_valid).sum()
        if invalidos > 0:
            gdf_chunk_pdet['geometry'] = gdf_chunk_pdet['geometry'].apply(lambda geom: make_valid(geom) if not geom.is_valid else geom)

        chunks_filtrados_y_limpios.append(gdf_chunk_pdet)

    print(f"-> Lote {i+1} procesado. Edificios retenidos en zona PDET: {len(gdf_chunk_pdet)}")

    del chunk, chunk_clean, gdf_chunk, gdf_chunk_pdet
    gc.collect()

# Consolidar resultado final
if chunks_filtrados_y_limpios:
    gdf_edificios_pdet = pd.concat(chunks_filtrados_y_limpios, ignore_index=True)
    gdf_edificios_pdet = gpd.GeoDataFrame(gdf_edificios_pdet, geometry='geometry', crs="EPSG:4326")
else:
    gdf_edificios_pdet = gpd.GeoDataFrame(crs="EPSG:4326")

print(f"\nRegistros originales analizados: {total_originales}")
print(f"Edificios limpios confinados al Excel PDET: {len(gdf_edificios_pdet)}\n")


# ==========================================
# 4. AUDITORÍA FINAL DE INTEGRIDAD Y NULOS
# ==========================================
print("=" * 50)
print("INFORME DE AUDITORÍA Y CALIDAD DE DATOS (PDET)")
print("=" * 50)

# Conteo de valores nulos por columna
print("Valores nulos por columna en el dataset final:")
nulos_por_columna = gdf_edificios_pdet.isna().sum()
for col, val in nulos_por_columna.items():
    print(f"{col:<20} {val}")

# Verificación de geometrías vacías
geometrias_vacias = gdf_edificios_pdet.geometry.is_empty.sum()
print(f"\nGeometrías vacías (is_empty): {geometrias_vacias}")

# Verificación de topología (geometrías aún inválidas)
geometrias_invalidas = (~gdf_edificios_pdet['geometry'].is_valid).sum()
print(f"Geometrías inválidas remanentes: {geometrias_invalidas}")

# Verificación de CRS
print(f"Sistema de Referencia de Coordenadas (CRS): {gdf_edificios_pdet.crs}")

# Tipo de dato de muestra
tipo_dato = gdf_edificios_pdet.dtypes.iloc[0] if not gdf_edificios_pdet.empty else 'N/A'
print(f"dtype general de muestra: {tipo_dato}")

print("=" * 50)
print("¡Auditoría finalizada. Listos para ingesta en MongoDB (2dsphere)!")
print("=" * 50)